'use strict';
// Development utility: measure visible artwork, preserving original PNG/SVG files.
// Run after replacing icon files. Requires the existing sharp development dependency.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),sharp=require('sharp');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const source=fs.readFileSync(path.join(root,'assets/js/data/icons.js'),'utf8');
 const images=vm.runInNewContext(source+'; iconImages;');
 const metrics={};
 for(const [icon,file]of Object.entries(images)){
  const {data,info}=await sharp(path.join(root,'assets/images/app_icons',file)).resize(512,512,{fit:'contain',background:'#00000000'}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  let left=info.width,top=info.height,right=0,bottom=0;
  for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>12){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  const size=Math.max(right-left+1,bottom-top+1);
  const round=value=>Math.round(value*1000)/1000;
  metrics[icon]={size:round(512/size*100),x:round(50-(left+right+1)/2/size*100),y:round(50-(top+bottom+1)/2/size*100)};
 }
 fs.writeFileSync(path.join(root,'assets/js/data/icon-metrics.js'),"'use strict';\n// Visible bounds generated by scripts/measure-icons.cjs. Source artwork is unchanged.\nconst iconMetrics = Object.freeze("+JSON.stringify(metrics,null,2)+');\n');
 console.log('Measured '+Object.keys(metrics).length+' icon assets.');
})().catch(error=>{console.error(error);process.exit(1)});
